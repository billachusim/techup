// Writes supabase/functions/_shared/service-prices.ts from src/data/services.ts, so the
// create-service-checkout edge function charges exactly the price the service page shows.
// Run after changing any service price: bunx tsx scripts/generate-service-prices.ts
// (tests/services/service-prices.test.ts fails if the two drift apart).
import { writeFileSync } from "fs";
import { SERVICES, businessPrice } from "../src/data/services";

const rows = SERVICES.map(
  (s) =>
    `  ${JSON.stringify(s.slug)}: { name: ${JSON.stringify(s.name)}, price: ${businessPrice(s)}, unit: ${JSON.stringify(s.unit)} },`,
);
const out = `// GENERATED by scripts/generate-service-prices.ts from src/data/services.ts. Do not edit by hand.
// Plain data with no imports, so the browser bundle and Deno edge functions can both import it.

export type ServicePrice = { name: string; price: number; unit: string };

export const SERVICE_PRICES: Record<string, ServicePrice> = {
${rows.join("\n")}
};

/** Most units one pay-now order can buy; bigger orders go through a custom brief. */
export const MAX_ORDER_QUANTITY = 50;
`;
writeFileSync("supabase/functions/_shared/service-prices.ts", out);
console.log(`service-prices.ts: ${SERVICES.length} services`);
