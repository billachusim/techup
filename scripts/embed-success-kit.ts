// Embeds the paid SIWES Success Kit into the server bundle, so it is served
// only by /api/success-kit to buyers who have paid, never as a public file.
// Run after replacing the zip:  bunx tsx scripts/embed-success-kit.ts
// (tests/payments/success-kit-download.test.ts fails if this was forgotten).
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const KIT_SOURCE = resolve("private/success-kit/siwes-success-kit-TFNG-v1.zip");
const OUT = resolve("src/lib/success-kit-file.server.ts");

const base64 = readFileSync(KIT_SOURCE).toString("base64");
writeFileSync(
  OUT,
  `// Generated by scripts/embed-success-kit.ts from private/success-kit/. Do not edit.\n` +
    `export const SUCCESS_KIT_FILENAME = "SIWES-Success-Kit-TechFacultyNG.zip";\n` +
    `export const SUCCESS_KIT_BASE64 =\n  "${base64}";\n`,
);
console.log(`Wrote ${OUT} (${base64.length} base64 chars)`);
